GROUNDING_RULES = """\
Grounding rules (mandatory):
- Use ONLY the supplied source material. Never fill any field from memory or
  general knowledge about the paper, the models, or the datasets.
- If the evidence is insufficient or ambiguous, answer "unclear". Never turn
  uncertainty into "yes" or "no".
- For every decision, quote a short supporting text snippet in "evidence" and
  give its "source_location" (section, table, figure, page, or URL). Mark
  "evidence_type" as "explicit" when the source states it directly and
  "inferred" when you deduce it; "none" when there is no evidence.
- Give a "confidence" in [0,1].
- Output a single JSON object and nothing else."""

TARGET_DEFINITION = """\
Target experiment type ("controlled same-student teacher comparison"):
  the SAME pre-SFT student model is supervised-fine-tuned SEPARATELY on
  agentic/interactive trajectories generated by EACH of >=2 teacher models on
  the same (or closely controlled) tasks, with a controlled SFT recipe/data
  budget, and a downstream score is reported SEPARATELY for each
  teacher-trained student. That yields a published teacher ranking.

NOT equivalent (do not count these as the target):
  - different students trained with different teachers
  - teachers generated different, uncontrolled task sets
  - all teacher trajectories mixed into one SFT dataset
  - teacher used only as an LLM judge, or only during RL
  - teacher routing / mixing without separate per-teacher SFT outcomes
  - different training budgets per teacher without a controlled comparison
  - teacher quality inferred without downstream SFT results
  - on-policy / per-step distillation (the teacher scores or corrects the
    student's own rollouts, e.g. reverse-KL, GKD, ReOPD) instead of plain SFT
    on teacher-generated trajectories"""


def prescreen_user(title: str, abstract: str, extra: str = "") -> str:
    return f"TITLE: {title}\n\nABSTRACT:\n{abstract}\n\n{extra}".strip()


def document_user(doc_title: str, source: str, text: str, focus: str = "") -> str:
    head = f"SOURCE: {source}\nTITLE: {doc_title}\n"
    if focus:
        head += f"\nFOCUS HINTS FROM SCREENING (verify, do not trust):\n{focus}\n"
    return head + "\n===== BEGIN SOURCE TEXT =====\n" + text + "\n===== END SOURCE TEXT ====="
